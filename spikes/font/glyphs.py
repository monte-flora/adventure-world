"""Shadowfall's own pixel font: every glyph, drawn by hand as text.

'#' is ink, '.' is empty. Each block starts with a header line:

    --- A          the character (or `space`, or `U+E000 heart` for a game symbol)
    --- a @3       '@3' = the first row drawn is row 3 (rows 0-2 are empty)

Row 0 is the top of a capital letter. The baseline is under the last cap row
(row 9 in BODY, row 6 in SMALL); rows below it are descenders. All rows of a glyph
have the same width, and that width is the glyph's ink width (spacing is added later).

Style rules (keep them when you add a glyph):
- BODY: upright strokes are 2 px thick, flat strokes 1 px (a little like pen-made
  gothic letters), corners are cut, and arches come to a point (look at A, n, m).
- SMALL: every stroke 1 px, corners cut. Made for HUD numbers and short labels;
  it has capitals only, so lower case is shown as capitals.
"""

