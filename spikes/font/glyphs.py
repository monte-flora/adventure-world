def parse(text):
    """Text blocks -> {codepoint: (first_row, [row strings])}."""
    glyphs, cp, start, rows = {}, None, 0, []

    def flush():
        if cp is not None:
            widths = {len(r) for r in rows}
            assert len(widths) == 1, f"U+{cp:04X}: rows differ in width {widths}"
            assert set("".join(rows)) <= {"#", "."}, f"U+{cp:04X}: bad character"
            glyphs[cp] = (start, rows)

    for line in text.splitlines():
        line = line.strip()
        if not line:
            continue
        if line.startswith("--- "):
            flush()
            parts = line[4:].split()
            tok = parts[0]
            if tok == "space":
                cp = 32
            elif tok.startswith("U+") and len(tok) > 2:
                cp = int(tok[2:], 16)
            else:
                assert len(tok) == 1, line
                cp = ord(tok)
            at = [p for p in parts[1:] if p.startswith("@")]
            start = int(at[0][1:]) if at else 0
            rows = []
        else:
            rows.append(line)
    flush()
    return glyphs
