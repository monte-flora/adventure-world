def bitmap(glyph, bw, bh):
    """-> (set of (x, y) ink pixels, left-trimmed; ink width)."""
    top, rows = glyph
    assert top + len(rows) <= bh, (glyph, "too tall")
    pts = set()
    for dy, row in enumerate(rows):
        assert len(row) <= bw and set(row) <= set("#."), (glyph, "bad row")
        pts |= {(x, top + dy) for x, ch in enumerate(row) if ch == "#"}
    if not pts:
        return pts, 0
    x0 = min(x for x, _ in pts)
    pts = {(x - x0, y) for x, y in pts}
    return pts, max(x for x, _ in pts) + 1


def build(name):
    glyphs, bw, bh, cw, ch, base, space = FONTS[name]
    chars = "".join(chr(i) for i in range(32, 127)) if name == "body" else " 0123456789+-/:x%"
    assert list(chars) == sorted(set(chars), key=chars.index) and set(glyphs) == set(chars), name
    cols = 16
    rows = -(-len(chars) // cols)
    img = surf(cols * cw, rows * ch)
    white = P["ink7"]
    adv, bm = {}, []
    for i, c in enumerate(chars):
        pts, w = bitmap(glyphs[c], bw, bh)
        ox, oy = (i % cols) * cw, (i // cols) * ch
        for x, y in pts:
            img.set_at((ox + x, oy + y), white)
        adv[c] = space if c == " " else w + 1
        bm.append((c, ox, oy, w))
    save_png(img, f"font/{name}.png")
    meta = {"image": f"{name}.png", "cell": [cw, ch], "baseline": base,
            "columns": cols, "advance": adv}
    if name == "body":
        meta["first"] = 32
    else:
        meta["chars"] = chars
    d = os.path.join(ART, "font")
    with open(os.path.join(d, f"{name}.json"), "w") as fh:
        json.dump(meta, fh, indent=1)
        fh.write("\n")
    gh = bh  # glyph height in the .fnt: the whole box, so descenders survive
    lines = [f'info face="shadowfall_{name}" size={gh} bold=0 italic=0 charset="" unicode=1 '
             f'stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0',
             f"common lineHeight={ch} base={base} scaleW={img.get_width()} scaleH={img.get_height()} "
             f"pages=1 packed=0",
             f'page id=0 file="{name}.png"',
             f"chars count={len(chars)}"]
    for c, x, y, w in bm:
        gw, gh_ = (w, gh) if w else (0, 0)
        lines.append(f"char id={ord(c)} x={x} y={y} width={gw} height={gh_} xoffset=0 yoffset=0 "
                     f"xadvance={adv[c]} page=0 chnl=15")
    with open(os.path.join(d, f"{name}.fnt"), "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"  font/{name}.json, font/{name}.fnt  {len(chars)} glyphs, cell {cw}x{ch}")


def text_surf(name, text, col=P["ink7"]):
    glyphs, bw, bh, cw, ch, base, space = FONTS[name]
    out = surf(len(text) * (bw + 1), ch)
    x = 0
    for c in text:
        pts, w = bitmap(glyphs.get(c, glyphs.get(c.upper(), G([]))), bw, bh)
        for px_, py in pts:
            out.set_at((x + px_, py), col)
        x += space if c == " " else w + 1
    return out


def preview(path):
    bg = P["ink1"]
    lines = [("body", "THE SHADOW KING RISES. 0123456789 the quick brown fox jumps over the lazy dog!?"),
             ("body", "ABCDEFGHIJKLMNOPQRSTUVWXYZ abcdefghijklmnopqrstuvwxyz"),
             ("body", "0123456789 !\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~"),
             ("num", "0123456789 + - / : x %  HP 12/30 x3 50%")]
    ss = [text_surf(n, t) for n, t in lines]
    W = max(s.get_width() for s in ss) + 8
    H = sum(s.get_height() + 2 for s in ss) + 6
    img = pygame.Surface((W, H))
    img.fill(bg)
    y = 3
    for s in ss:
        img.blit(s, (4, y))
        y += s.get_height() + 2
    pygame.image.save(pygame.transform.scale(img, (W * 4, H * 4)), path)
    print("  preview", path)


def main():
    for name in FONTS:
        build(name)


if __name__ == "__main__":
    if len(sys.argv) > 2 and sys.argv[1] == "--preview":
        preview(sys.argv[2])
    else:
        main()
